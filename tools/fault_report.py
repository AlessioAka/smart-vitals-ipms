"""Replay a messy feed through the API and write docs/results/fault_report.md (R9 evidence).

    python tools/fault_report.py
"""
import sys
from collections import Counter
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src import config
from tests.helpers import auth
from tests.test_faults import replay

CLINICIANS = ("C01", "C02", "C03", "C04")


def main():
    lines = ["# Fault report (generated by `python tools/fault_report.py`)", "",
             "Same 20 simulated patients, 150 simulated minutes, seed 11. Numbers are from SIMULATED data.", ""]
    for use_edge in (True, False):
        c, replies, observed = replay(use_edge=use_edge)
        truth = {o["reading_id"]: o["true_label"] for o in observed}
        counts = Counter((ev["fault"] or "clean", code, body.get("outcome")) for ev, code, body in replies)
        alerts = [a for cid in CLINICIANS for a in c.get("/alerts", headers=auth(c, cid)).get_json()]
        glitch_false = sum(1 for ev, code, body in replies if ev["fault"] == "glitch" and body.get("alert")
                           and truth[ev["reading"]["reading_id"]] == "Normal")
        dup_ok = sum(1 for ev, code, body in replies if ev["fault"] == "duplicate" and code == 200)
        dup_all = sum(1 for ev, *_ in replies if ev["fault"] == "duplicate")
        # reading level: of on-time, first-copy readings that are truly Critical, how many were labelled Critical?
        crit = [(body.get("status")) for ev, code, body in replies
                if ev["fault"] != "duplicate" and code == 201 and not body.get("late")
                and truth[ev["reading"]["reading_id"]] == "Critical"]
        # episode level
        by_pt = {}
        for a in alerts:
            by_pt.setdefault(a["patient_id"], []).append(datetime.fromisoformat(a["ts"]))
        eps, cur = [], None
        for o in sorted(observed, key=lambda o: (o["patient_id"], o["minute"])):
            if o["true_label"] == "Critical":
                if cur and cur["p"] == o["patient_id"] and o["minute"] - cur["e"] <= 2:
                    cur["e"] = o["minute"]
                else:
                    cur = {"p": o["patient_id"], "s": o["minute"], "e": o["minute"]}
                    eps.append(cur)
        t0 = datetime.fromisoformat(config.SIM_START)
        caught = sum(1 for e in eps if any(t0 + timedelta(minutes=e["s"] - 1) <= t <= t0 + timedelta(minutes=e["e"] + 10)
                                           for t in by_pt.get(e["p"], [])))
        lines += [f"## Edge range check {'ON' if use_edge else 'OFF'}", "",
                  f"- messages sent: {len(replies)}; server errors (5xx): {sum(code >= 500 for _, code, _ in replies)}",
                  f"- resent copies: {dup_all}; answered `200 duplicate`: {dup_ok}",
                  f"- alerts raised: {len(alerts)}; alerts sharing a reading_id: {len(alerts) - len({a['reading_id'] for a in alerts})}",
                  f"- false alerts caused by a glitched reading of a healthy patient: {glitch_false}",
                  f"- glitched readings refused with 422: {sum(1 for ev, code, _ in replies if ev['fault'] == 'glitch' and code == 422)} "
                  f"of {sum(1 for ev, *_ in replies if ev['fault'] == 'glitch')}",
                  f"- on-time truly-Critical readings labelled Critical: {sum(s == 'Critical' for s in crit)} of {len(crit)}",
                  f"- true Critical episodes with an alert for that patient (within the episode +10 min): {caught} of {len(eps)}",
                  "", "| fault | HTTP | outcome | messages |", "|---|---|---|---|"]
        for (fault, code, outcome), n in sorted(counts.items()):
            lines.append(f"| {fault} | {code} | {outcome} | {n} |")
        lines.append("")
    (config.RESULTS_DIR / "fault_report.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
