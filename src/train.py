"""Train, compare and save the model (R3, Output 1 and Output 4).

    python -m src.train

Writes docs/results/model_comparison.md and docs/results/confusion_matrices.png,
and saves the chosen model to models/ for the API.
"""
import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from src import config, drift, model as M
from src.pipeline import FEATURES, clean_and_featurise, prepare, range_check

TARGET_RECALL_CRITICAL = 0.90  # the target in the design plan form's example


def load_training_frame() -> pd.DataFrame:
    """The training CSV after the SAME cleaning + feature pipeline the API uses live."""
    return clean_and_featurise(pd.read_csv(config.DATA_PATH))


def run() -> dict:
    df = load_training_frame()
    # Hold back whole PATIENTS: the test set contains people the model has never seen,
    # which is how it will be used in the clinic (the guide's "trap": splitting rows is too kind).
    train, test = M.split_by_patient(df)
    X_tr, y_tr = train[FEATURES], train["true_label"]   # patient_id is NOT a feature
    X_te, y_te = test[FEATURES], test["true_label"]

    models = {"baseline (always Normal)": M.make_baseline(),
              "logistic regression": M.make_logreg(),
              "random forest": M.make_forest()}
    results = {}
    for name, m in models.items():
        m.fit(X_tr, y_tr)
        results[name] = M.evaluate(m, X_te, y_te)

    # The leak: split ROWS at random and the forest looks better than it is.
    r_train, r_test = M.split_random_rows(df)
    leaky = M.make_forest().fit(r_train[FEATURES], r_train["true_label"])
    leak_acc = M.evaluate(leaky, r_test[FEATURES], r_test["true_label"])["accuracy"]

    # Choose between the two real models: best recall for Critical, then macro F1.
    # Recall for Critical comes first because a MISSED Critical is the costly mistake (R4, R9).
    candidates = ["logistic regression", "random forest"]
    best = max(candidates, key=lambda n: (results[n]["recall_critical"], results[n]["macro_f1"]))
    M.save_model(models[best], best, results[best])

    # Drift monitoring: remember what the TRAINING patients' readings looked like (values as the
    # API stores them: impossible values removed, nothing filled in), so the dashboard can tell
    # when live readings stop looking like this.
    raw = range_check(prepare(pd.read_csv(config.DATA_PATH)))
    drift.save_reference(drift.build_reference(raw[raw["patient_id"].isin(set(train["patient_id"]))]))

    out = {"train_patients": int(train["patient_id"].nunique()),
           "test_patients": int(test["patient_id"].nunique()),
           "train_rows": len(train), "test_rows": len(test),
           "results": results, "random_row_split_accuracy": leak_acc,
           "chosen": best, "target_recall_critical": TARGET_RECALL_CRITICAL}
    write_report(out)
    plot_confusions(results)
    return out


def write_report(out: dict) -> None:
    lines = ["# Model comparison (generated by `python -m src.train`)", "",
             "Do not edit by hand: rerun the command. Numbers come from SIMULATED data with "
             "RULE-MADE labels (see docs/assumptions.md).", "",
             f"Split by patient: {out['train_patients']} training patients "
             f"({out['train_rows']} readings), {out['test_patients']} unseen test patients "
             f"({out['test_rows']} readings).", "",
             "| Model | Accuracy | Macro F1 | Recall Normal | Recall Warning | Recall Critical | "
             "Precision Critical | F1 Critical |",
             "|---|---|---|---|---|---|---|---|"]
    for name, r in out["results"].items():
        lines.append(f"| {name} | {r['accuracy']:.3f} | {r['macro_f1']:.3f} | {r['recall']['Normal']:.3f} | "
                     f"{r['recall']['Warning']:.3f} | {r['recall']['Critical']:.3f} | "
                     f"{r['precision']['Critical']:.3f} | {r['f1']['Critical']:.3f} |")
    lines += ["", f"Chosen model: **{out['chosen']}** (best recall for Critical, then macro F1). "
              f"Target recall for Critical: {out['target_recall_critical']:.2f}.", "",
              f"Random-row split (leaky) accuracy for the forest: {out['random_row_split_accuracy']:.3f} "
              "- compare with the patient-split accuracy above.", "",
              "## Confusion matrices (rows = true, columns = predicted: Normal, Warning, Critical)", ""]
    for name, r in out["results"].items():
        lines += [f"**{name}**", "", "```"] + ["  ".join(f"{v:6d}" for v in row) for row in r["confusion_matrix"]] + ["```", ""]
    config.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.RESULTS_DIR / "model_comparison.md").write_text("\n".join(lines), encoding="utf-8")
    (config.RESULTS_DIR / "model_comparison.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    write_first_model(out)


def write_first_model(out: dict) -> None:
    """docs/results/first_model.md: guide Step 5, item 9 - the baseline vs the random forest."""
    base, forest = out["results"]["baseline (always Normal)"], out["results"]["random forest"]
    lines = ["# First model: baseline vs random forest (generated by `python -m src.train`)", "",
             "Simulated data, rule-made labels (docs/assumptions.md A3). Test set = "
             f"{out['test_patients']} patients the model has never seen ({out['test_rows']} readings).", "",
             "| Measure | Baseline (always Normal) | Random forest |", "|---|---|---|"]
    for label, key in [("Accuracy", "accuracy"), ("Macro F1", "macro_f1"), ("Recall for Critical", "recall_critical")]:
        lines.append(f"| {label} | {base[key]:.3f} | {forest[key]:.3f} |")
    for label in config.LABELS:
        lines.append(f"| Precision {label} | {base['precision'][label]:.3f} | {forest['precision'][label]:.3f} |")
        lines.append(f"| Recall {label} | {base['recall'][label]:.3f} | {forest['recall'][label]:.3f} |")
        lines.append(f"| F1 {label} | {base['f1'][label]:.3f} | {forest['f1'][label]:.3f} |")
    lines += ["", f"The baseline is right {base['accuracy']:.0%} of the time but finds "
              f"{base['recall_critical']:.0%} of Critical readings. The forest finds "
              f"{forest['recall_critical']:.1%} of Critical readings in unseen patients "
              f"(target {out['target_recall_critical']:.0%}).", "",
              f"Splitting rows at random instead would report {out['random_row_split_accuracy']:.3f} accuracy "
              f"for the forest, against {forest['accuracy']:.3f} on the patient split: too kind, because the model "
              "has already met those patients.", "",
              "Confusion matrices: `docs/results/confusion_matrices.png` and `docs/results/model_comparison.md`."]
    (config.RESULTS_DIR / "first_model.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def plot_confusions(results: dict) -> None:
    fig, axes = plt.subplots(1, len(results), figsize=(4.2 * len(results), 4))
    for ax, (name, r) in zip(axes, results.items()):
        cm = r["confusion_matrix"]
        ax.imshow(cm, cmap="Blues")
        ax.set_title(name, fontsize=10)
        ax.set_xticks(range(3), config.LABELS, fontsize=8)
        ax.set_yticks(range(3), config.LABELS, fontsize=8)
        ax.set_xlabel("Predicted")
        ax.set_ylabel("True")
        top = max(max(row) for row in cm) or 1
        for i in range(3):
            for j in range(3):
                ax.text(j, i, cm[i][j], ha="center", va="center",
                        color="white" if cm[i][j] > top / 2 else "black")
    fig.tight_layout()
    fig.savefig(config.RESULTS_DIR / "confusion_matrices.png", dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    o = run()
    for n, r in o["results"].items():
        print(f"{n:28s} acc={r['accuracy']:.3f} recall_critical={r['recall_critical']:.3f} macroF1={r['macro_f1']:.3f}")
    print("chosen:", o["chosen"], "| leaky random-row accuracy:", round(o["random_row_split_accuracy"], 3))
